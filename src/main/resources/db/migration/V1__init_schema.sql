-- =====================================================================
-- Thoth: схема для разделения ресторанного чека
-- Каскад: users -> sessions -> (items, guests) -> item_assignments
-- Всё удаление выполняется самой БД (ON DELETE CASCADE): один
-- DELETE FROM sessions убирает позиции, гостей и их доли без загрузки в JPA.
-- В PostgreSQL FK-колонки НЕ индексируются автоматически, поэтому индексы
-- на них заданы явно — иначе каскад делает seq scan по дочерним таблицам.
-- =====================================================================

CREATE TABLE users
(
    telegram_id BIGINT      PRIMARY KEY,
    username    VARCHAR(32),                          -- в Telegram username до 32 символов, может отсутствовать
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE sessions
(
    id         UUID        PRIMARY KEY,               -- UUID: безопасно передавать в startapp-параметр Mini App
    user_id    BIGINT      NOT NULL
        CONSTRAINT fk_sessions_user REFERENCES users (telegram_id) ON DELETE CASCADE,
    status     VARCHAR(20) NOT NULL
        CONSTRAINT chk_sessions_status
            CHECK (status IN ('AWAITING_GUESTS', 'AWAITING_PHOTO', 'PROCESSING', 'READY')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Поиск активной сессии пользователя (самая свежая первой) + каскад от users
CREATE INDEX idx_sessions_user_created ON sessions (user_id, created_at DESC);
-- Для периодической очистки старых сессий
CREATE INDEX idx_sessions_created_at ON sessions (created_at);

CREATE TABLE items
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id UUID           NOT NULL
        CONSTRAINT fk_items_session REFERENCES sessions (id) ON DELETE CASCADE,
    name       VARCHAR(255)   NOT NULL,
    price      NUMERIC(12, 2) NOT NULL
        CONSTRAINT chk_items_price CHECK (price >= 0),
    currency   VARCHAR(3)     NOT NULL
        CONSTRAINT chk_items_currency CHECK (currency ~ '^[A-Z]{3}$')   -- ISO 4217: RUB, USD, EUR...
);

CREATE INDEX idx_items_session ON items (session_id);

CREATE TABLE guests
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id UUID         NOT NULL
        CONSTRAINT fk_guests_session REFERENCES sessions (id) ON DELETE CASCADE,
    name       VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_guests_session ON guests (session_id);

CREATE TABLE item_assignments
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id     BIGINT        NOT NULL
        CONSTRAINT fk_assignments_item REFERENCES items (id) ON DELETE CASCADE,
    guest_id    BIGINT        NOT NULL
        CONSTRAINT fk_assignments_guest REFERENCES guests (id) ON DELETE CASCADE,
    share_ratio NUMERIC(3, 2) NOT NULL
        CONSTRAINT chk_assignments_share CHECK (share_ratio > 0 AND share_ratio <= 1),
    -- один гость — одна доля на позицию; индекс также покрывает FK item_id
    CONSTRAINT uq_assignments_item_guest UNIQUE (item_id, guest_id)
);

-- Покрывает FK guest_id (каскад при удалении гостя) и выборку "что ест гость"
CREATE INDEX idx_assignments_guest ON item_assignments (guest_id);
